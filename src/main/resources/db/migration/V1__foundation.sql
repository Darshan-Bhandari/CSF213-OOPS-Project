CREATE TABLE user_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 display_name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(trim(email))),
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('EMPLOYEE','TECHNICIAN','ADMIN')),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE technician_profiles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE REFERENCES user_accounts(id),
 available BOOLEAN NOT NULL DEFAULT TRUE,
 capacity INTEGER NOT NULL DEFAULT 5 CHECK (capacity BETWEEN 1 AND 100)
);
CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE it_services (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 criticality INTEGER NOT NULL CHECK (criticality BETWEEN 1 AND 3),
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE sla_policies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 service_id BIGINT REFERENCES it_services(id),
 priority VARCHAR(2) NOT NULL CHECK (priority IN ('P1','P2','P3','P4')),
 response_seconds INTEGER NOT NULL CHECK (response_seconds > 0),
 resolution_seconds INTEGER NOT NULL CHECK (resolution_seconds >= response_seconds)
);
CREATE UNIQUE INDEX unique_default_sla ON sla_policies(priority) WHERE service_id IS NULL;
CREATE UNIQUE INDEX unique_service_sla ON sla_policies(service_id,priority) WHERE service_id IS NOT NULL;
CREATE TABLE audit_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT REFERENCES user_accounts(id),
 action VARCHAR(80) NOT NULL,
 subject VARCHAR(150) NOT NULL,
 description VARCHAR(2000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX audit_entries_created_idx ON audit_entries(created_at);
